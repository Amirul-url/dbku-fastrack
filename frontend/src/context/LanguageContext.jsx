const LanguageContext = createContext(null);

function getInitialLanguage() {
  if (typeof window === "undefined") return "en";

  const stored = localStorage.getItem(STORAGE_KEY);
  return stored === "en" || stored === "ms" ? stored : "en";
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(getInitialLanguage);

  useEffect(() => {
    document.documentElement.lang = language === "ms" ? "ms-MY" : "en";
  }, [language]);

  function setLanguage(nextLanguage) {
    const normalized = nextLanguage === "en" ? "en" : "ms";
    setLanguageState(normalized);
    localStorage.setItem(STORAGE_KEY, normalized);
    document.documentElement.lang = normalized === "ms" ? "ms-MY" : "en";
  }

  const value = useMemo(() => {
    function t(key, fallback, replacements = null) {
      const template = (
        dictionaries[language]?.[key] ||
        dictionaries.en[key] ||
        fallback ||
        key
      );

      if (!replacements || typeof template !== "string") {
        return template;
      }

      return template.replace(/\{(\w+)\}/g, (match, name) =>
        Object.prototype.hasOwnProperty.call(replacements, name)
          ? String(replacements[name])
          : match
      );
    }

    return {
      language,
      setLanguage,
      t,
    };
  }, [language]);

  return (
    <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);

  if (!context) {
    throw new Error("useLanguage must be used inside LanguageProvider");
  }

  return context;
}
